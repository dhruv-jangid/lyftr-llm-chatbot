"""Everything LiteLLM: the key pool, automatic failover, caching and the
X-Simulate-Failure test hook.

How it works
------------
* Each API key becomes its own LiteLLM Router "model group" named key_1, key_2...
  All groups point at the same model (LLM_MODEL), only the api_key differs.
* Router(fallbacks=[{"key_1": ["key_2", ...]}]) tells LiteLLM: if key_1 fails
  (429 / quota / 5xx / any provider error) try key_2, then key_3, ...
  num_retries=0 so a failing key is not retried, we move on immediately.
* litellm.cache = Cache(type="local") turns on LiteLLM's in-memory cache.
  The cache key is built by LiteLLM from the model + the full message list.
  caching_groups makes all key groups share ONE cache, so a reply generated by
  key_2 is still a cache hit for a later request that starts at key_1.
* Failure simulation builds a short-lived Router for that one request in which
  the chosen keys use LiteLLM's `mock_response` to raise a 429 / 5xx error.
  Nothing global changes, so other requests are unaffected.
"""
import logging
import re
from dataclasses import dataclass

import litellm
from litellm import Router
from litellm.caching.caching import Cache

from .config import settings

logger = logging.getLogger("app.llm")

# Keep LiteLLM quiet: no debug banners and no provider tracebacks in our logs.
litellm.suppress_debug_info = True
for _name in ("LiteLLM", "LiteLLM Router", "LiteLLM Proxy"):
    logging.getLogger(_name).setLevel(logging.CRITICAL)

# Turn on LiteLLM's built-in in-memory response cache.
litellm.cache = Cache(type="local")

SUPPORTED_SIMULATED_STATUSES = {429, 500, 502, 503}


class AllProvidersFailed(Exception):
    """Raised when every key in the pool failed."""


class InvalidSimulationHeader(ValueError):
    pass


@dataclass
class LLMResult:
    reply: str
    resolution_source: str  # LIVE_INFERENCE or LLM_CACHE
    input_tokens: int
    output_tokens: int
    key_id: str | None
    fallback_attempts: int


def _mock_for_status(status: int) -> str:
    # LiteLLM's mock_response raises a real litellm exception:
    #   "litellm.RateLimitError"      -> HTTP 429
    #   "litellm.InternalServerError" -> HTTP 5xx
    return "litellm.RateLimitError" if status == 429 else "litellm.InternalServerError"


def build_router(simulated_failures: dict[str, int] | None = None) -> Router:
    simulated_failures = simulated_failures or {}
    model_list = []
    for key_id, api_key in zip(settings.key_ids, settings.api_keys):
        params = {
            "model": settings.llm_model,
            "api_key": api_key,
            "timeout": settings.llm_timeout,
        }
        if settings.llm_api_base:
            params["api_base"] = settings.llm_api_base
        if key_id in simulated_failures:
            params["mock_response"] = _mock_for_status(simulated_failures[key_id])
        model_list.append(
            {"model_name": key_id, "litellm_params": params, "model_info": {"id": key_id}}
        )

    ids = settings.key_ids
    return Router(
        model_list=model_list,
        fallbacks=[{ids[0]: ids[1:]}] if len(ids) > 1 else [],
        num_retries=0,               # don't retry a failing key, fail over instead
        disable_cooldowns=True,      # always try keys in order key_1, key_2, ...
        caching_groups=[tuple([settings.llm_model] + ids)],  # one shared cache
    )


router = build_router()


def parse_simulation_header(value: str | None) -> dict[str, int]:
    """'key_1=429,key_2=500' -> {'key_1': 429, 'key_2': 500}; '*=429' -> all keys."""
    if not value or not value.strip():
        return {}
    result: dict[str, int] = {}
    for part in value.split(","):
        part = part.strip()
        if not part:
            continue
        match = re.fullmatch(r"(\*|key_\d+)\s*=\s*(\d{3})", part)
        if not match:
            raise InvalidSimulationHeader(f"invalid X-Simulate-Failure entry: {part!r}")
        target, status = match.group(1), int(match.group(2))
        if status not in SUPPORTED_SIMULATED_STATUSES:
            raise InvalidSimulationHeader(f"unsupported simulated status: {status}")
        targets = settings.key_ids if target == "*" else [target]
        for key_id in targets:
            if key_id in settings.key_ids:  # ignore ids that don't exist
                result[key_id] = status
    return result


async def complete(messages: list[dict], simulated_failures: dict[str, int]) -> LLMResult:
    """Send the full message list to the LLM through the LiteLLM router."""
    if not settings.api_keys:
        raise AllProvidersFailed()
    kwargs ={"model": settings.key_ids[0], "messages": messages, "caching": True}

    if simulated_failures:
        active_router = build_router(simulated_failures)
        # A simulation request must really reach the keys to demonstrate
        # failover, so we skip cache *reads* (the reply is still cached).
        kwargs["cache"] = {"no-cache": True}
    else:
        active_router = router

    try:
        response = await active_router.acompletion(**kwargs)
    except Exception as exc:  # every key failed (429 / quota / 5xx / auth ...)
        logger.warning("all providers failed: %s", type(exc).__name__)
        raise AllProvidersFailed() from exc

    reply = (response.choices[0].message.content or "").strip()
    if not reply:
        raise AllProvidersFailed()

    hidden = getattr(response, "_hidden_params", {}) or {}
    cache_hit = bool(hidden.get("cache_hit"))
    usage = getattr(response, "usage", None)
    input_tokens = int(getattr(usage, "prompt_tokens", 0) or 0)
    output_tokens = int(getattr(usage, "completion_tokens", 0) or 0)

    if cache_hit:
        return LLMResult(reply, "LLM_CACHE", input_tokens, output_tokens, None, 0)

    key_id = hidden.get("model_id")  # we set model_info.id = key_1 / key_2 ...
    # Keys are always tried in order, so the position of the key that answered
    # equals the number of keys that failed before it.
    fallback_attempts = settings.key_ids.index(key_id) if key_id in settings.key_ids else 0
    return LLMResult(reply, "LIVE_INFERENCE", input_tokens, output_tokens, key_id, fallback_attempts)
